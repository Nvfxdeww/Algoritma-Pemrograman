// C++ program to illustrate if-else statement
#include <iostream>
using namespace std;

int main() {
    int i = 25;
    
    if (i > 15) {
        cout << "i is greater than 15" << endl;
    } else {
        cout << "i is smaller than or equal to 15" << endl; 
    }
    
    return 0;
}